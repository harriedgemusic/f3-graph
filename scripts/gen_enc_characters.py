def norm_space(s: str) -> str:
    return SPACE_RE.sub(" ", (s or "")).strip()


def strip_raw_markup(text: str) -> str:
    """Ensure zero raw wikitext, XML/HTML, replacement chars, or engine tokens remain."""
    if not text:
        return ""
    s = text.replace("\ufffd", "")
    s = s.replace("&PCName;", "Одинокого Путника")
    s = re.sub(r"\{\{[^}]*\}\}", "", s)
    s = s.replace("{{", "").replace("}}", "")
    s = s.replace("[[", "").replace("]]", "")
    s = re.sub(r"<ref[^>]*>.*?</ref>", "", s, flags=re.DOTALL | re.IGNORECASE)
    s = re.sub(r"</?(?:ref|div|span|font|br|p|center|small|big)[^>]*>", " ", s, flags=re.IGNORECASE)
    s = re.sub(r"\[\d+\]", "", s)
    s = s.replace("Обитатель Пустоши (", "Обитатель Столичной Пустоши (")
    return norm_space(s)


def trim_sentences(text: str, max_chars: int = 720) -> str:
    """Trim prose cleanly at sentence boundaries without cutting mid-sentence."""
    text = norm_space(text)
    if not text:
        return ""
    if len(text) <= max_chars:
        if text[-1] not in ".!?…»\"":
            text += "."
        text = re.sub(r"([!?])\.", r"\1", text)
        text = re.sub(r"(?<!\.)\.\.(?!\.)", ".", text)
        return text
    sents = SENT_SPLIT_RE.split(text)
    out: list[str] = []
    cur_len = 0
    for s in sents:
        s = s.strip()
        if not s:
            continue
        add_len = len(s) + (1 if out else 0)
        if cur_len + add_len <= max_chars:
            out.append(s)
            cur_len += add_len
        elif not out:
            cut = s[: max_chars - 1]
            idx = max(cut.rfind(". "), cut.rfind("; "), cut.rfind(", "), cut.rfind(" "))
            if idx > max_chars // 2:
                cut = cut[:idx]
            out.append(cut.rstrip(" ,;:-") + ".")
            break
        else:
            break
    res = " ".join(out).strip()
    if res and res[-1] not in ".!?…»\"":
        res += "."
    res = re.sub(r"([!?])\.", r"\1", res)
    res = re.sub(r"(?<!\.)\.\.(?!\.)", ".", res)
    return res


def strip_meta_lead_clauses(first_sent: str) -> tuple[str, str]:
    """Strip meta game-appearance clauses after 'Name — ' and return (appositive_role, cleaned_sentence)."""
    s = re.sub(r"\s*\([^)]*(?:Fallout|в\s+игре|именуется|англ\.|ориг\.)[^)]*\)", "", first_sent, flags=re.I)
    m = re.match(r"^([^—–\n]{1,95}?)\s+(?:[—–]|-)\s+(.+)$", s)
    if not m:
        return "", ""
    subj = m.group(1).strip(" ,;:-.")
    pred = m.group(2).strip().rstrip(".")
    clauses = [c.strip() for c in re.split(r"[;,]", pred) if c.strip()]
    while clauses and META_LEAD_CLAUSE_RE.search(clauses[0]):
        clauses.pop(0)
    cleaned_clauses: list[str] = []
    for c in clauses:
        if META_LEAD_CLAUSE_RE.search(c):
            continue
        c = re.sub(
            r"^(?:где\s+он[аи]?\s+|который\s+|которая\s+|которое\s+|которые\s+)?(?:является|представляет\s+собой|идентифицируется\s+как)\s+",
            "",
            c,
            flags=re.I,
        )
        if re.match(r"^(?:котор(?:ый|ая|ое|ые)|тела\s+которых|член(?:ы)?\s+котор|а\s+в\s+22)\b", c, re.I):
            continue
        cleaned_clauses.append(c)
    if not cleaned_clauses:
        return "", ""
    if len(cleaned_clauses[0].split()) <= 2 and len(cleaned_clauses) >= 2:
        app = f"{cleaned_clauses[0]}, {cleaned_clauses[1]}"
    else:
        app = cleaned_clauses[0]
    app = re.sub(r"^(?:в|на\s+момент|по\s+состоянию\s+на)\s+22\d\d\s+год[ауе]?\s+", "", app, flags=re.I)
    app = re.sub(r"\s+(?:на\s+момент|в|по\s+состоянию\s+на)\s+22\d\d\s+год[ауе]?\b.*$", "", app, flags=re.I).strip(" ,;:-.")
    app = re.sub(r"^(?:проживающий|живущий|обитающий)\s+в\s+", "житель ", app, flags=re.I)
    app = re.sub(r"^(?:проживающая|живущая|обитающая)\s+в\s+", "жительница ", app, flags=re.I)
    app = re.sub(r",\s*(?:проживающий|проживающая|живущий|живущая|обитающий|обитающая)\s+в\s+", " из ", app, flags=re.I)
    rem = ", ".join(cleaned_clauses).strip(" ,;:-.")
    full_sent = f"{subj} — {rem}." if len(rem) >= 10 else ""
    return app, full_sent


def clean_wiki_lead(raw_lead: str) -> tuple[str, str]:
    """Return (cleaned_lead_text, appositive_descriptor) stripped of hatnotes, epigraphs, and boilerplate."""
    if not raw_lead:
        return "", ""

    # Strip leading hatnote lines first
    pre_lines = [l.strip() for l in raw_lead.splitlines() if l.strip()]
    while pre_lines and HATNOTE_LINE_RE.match(pre_lines[0]):
        pre_lines.pop(0)
    joined_pre = "\n".join(pre_lines).strip()

    # Strip multi-line leading epigraph quotes ("«...» — Author")
    joined_pre = re.sub(r"^\s*«[^»]{1,1500}»(?:\s*[—–-][^\n]+)?\s*", "", joined_pre, flags=re.DOTALL)

    lines = [l.strip() for l in joined_pre.splitlines() if l.strip()]
    kept: list[str] = []
    for line in lines:
        if HATNOTE_LINE_RE.match(line):
            continue
        if EPIGRAPH_LINE_RE.match(line) and not kept:
            continue
        if line.startswith("«") and "—" in line and not kept and len(line) < 340:
            continue
        kept.append(line)

    text = norm_space(" ".join(kept))
    text = ANGL_PARENS_RE.sub("", text)
    text = strip_raw_markup(text)
    text = re.sub(r"\b([а-яА-ЯёЁ]{1,4})\s+\1\b", r"\1", text)

    # Remove trailing "; также является персонажем Fallout Shelter..."
    text = re.sub(r"[;,]\s*также\s+(?:является|упоминается)\s+[^.]+", "", text, flags=re.IGNORECASE)

    raw_sents = [s.strip() for s in SENT_SPLIT_RE.split(text) if s.strip()]
    if not raw_sents:
        return "", ""

    appositive, cleaned_first = strip_meta_lead_clauses(raw_sents[0])
    out_sents: list[str] = []
    for idx, sent in enumerate(raw_sents):
        if HATNOTE_LINE_RE.match(sent):
            continue
        if idx == 0:
            if cleaned_first and not META_SENTENCE_RE.search(cleaned_first):
                out_sents.append(cleaned_first)
            elif not META_LEAD_CLAUSE_RE.search(sent) and not META_SENTENCE_RE.search(sent) and len(sent) >= 35:
                out_sents.append(sent)
        else:
            if META_SENTENCE_RE.search(sent):
                continue
            out_sents.append(sent)

    return norm_space(" ".join(out_sents)), appositive


def filter_wiki_sections(raw_sections: list[dict[str, str]]) -> dict[str, str]:
    """Filter and clean wiki sections into normalized topic buckets."""
    buckets: dict[str, list[str]] = defaultdict(list)
    for sec in raw_sections or []:
        heading = norm_space(sec.get("heading", ""))
        hlow = heading.lower().replace("ё", "е")
        if hlow in SKIP_WIKI_SECTIONS:
            continue
        if any(
            sk in hlow
            for sk in ("fallout 4", "fallout: new vegas", "fallout 2", "fallout tactics", "fallout shelter", "van buren", "телесериал", "вырезанный контент")
        ):
            continue
        if hlow.startswith(("за кулисами", "баги", "галерея", "появление", "полевой отчет", "отдельные персонажи", "именованные протектроны", "цитаты", "коды")):
            continue
        body = strip_raw_markup(sec.get("text", ""))
        if not body:
            continue
        is_quest_sec = "квест" in hlow
        clean_lines: list[str] = []
        skip_sub = False
        for ln in sec.get("text", "").splitlines():
            ln = strip_raw_markup(ln.lstrip("*•- \t"))
            if not ln or HATNOTE_LINE_RE.match(ln):
                continue
            # Check inline subheading lines like "Fallout 4:" or "Fallout Shelter:"
            if ln.endswith(":") and len(ln) < 75 and not any(p in ln[:-1] for p in (".", "!", "?")):
                sub_low = ln.lower().replace("ё", "е")
                if sub_low in ("fallout:", "fallout и fallout 2:") or any(sk in sub_low for sk in SKIP_SUBSECTION_HEADERS):
                    skip_sub = True
                else:
                    skip_sub = False
                continue
            if skip_sub:
                continue
            if META_SENTENCE_RE.search(ln):
                continue
            if is_quest_sec:
                if " • " in ln:
                    qpart, rest = ln.split(" • ", 1)
                    qpart = qpart.strip(" «»\"'.,;:-")
                    rest = rest.strip()
                    if qpart and rest and len(qpart) < 70:
                        ln = f"«{qpart}» — {rest}"
                if ln.endswith(":"):
                    continue
                if re.match(r"^[«\"'][^»\"']+[»\"']\.?$", ln):
                    continue
                if (
                    len(ln.split()) <= 6
                    and "—" not in ln
                    and not re.search(
                        r"\b(?:может|будет|является|помогает|просит|даёт|встречается|появляется|можно|нужно|если|после|во\s+время)\b",
                        ln,
                        re.I,
                    )
                ):
                    continue
            if ln.endswith(":"):
                ln = ln[:-1].rstrip()
                if not ln:
                    continue
            # Ensure standalone bullet lines end with sentence punctuation so they don't glue together
            if ln[-1] not in ".!?…":
                ln += "."
            clean_lines.append(ln)
        joined = norm_space(" ".join(clean_lines))
        joined = joined.replace(" • ", ". ").replace("• ", "")
        joined = ANGL_PARENS_RE.sub("", joined)
        joined = re.sub(r"\b([а-яА-ЯёЁ]{1,4})\s+\1\b", r"\1", joined)
        sents = [s.strip() for s in SENT_SPLIT_RE.split(joined) if s.strip() and not META_SENTENCE_RE.search(s)]
        cleaned_body = norm_space(" ".join(sents))
        if len(cleaned_body) < 25:
            continue

        if any(k in hlow for k in ("описан", "истори", "биограф", "присоединен", "до мутации", "fallout 3", "напарник", "ранги", "резидент", "общая информац", "статус ", "цитадел", "очистител", "2277", "mothership zeta", "получен", "находк")):
            buckets["lore"].append(cleaned_body)
        elif is_quest_sec:
            buckets["quests"].append(cleaned_body)
        elif any(k in hlow for k in ("распорядок", "распис", "поведен", "характер", "личность", "отношен", "взаимодейств", "язык", "друг животн")):
            buckets["behavior"].append(cleaned_body)
        elif any(k in hlow for k in ("замет", "дополнит")):
            buckets["notes"].append(cleaned_body)
        elif any(k in hlow for k in ("инвентар", "экипиров", "ассортимент", "продаваемые")):
            buckets["gear"].append(cleaned_body)
        elif any(k in hlow for k in ("локац", "местонахожден", "местообитан", "случайные встреч")):
            buckets["locations"].append(cleaned_body)
        elif any(k in hlow for k in ("характеристик", "специфик", "виды", "разновидност", "биолог", "конструкц", "трофе", "уничтожен", "вариант")):
            buckets["specs"].append(cleaned_body)

    return {k: " ".join(v) for k, v in buckets.items() if v}


def preclean_raw_wikitext(wt: str) -> str:
    """Fix self-closing <ref/> order, strip Fallout Shelter / cut-content blocks, and expand {{СДФ}} dialogue verbs."""
    if not wt:
        return ""
    wt = re.sub(r"<ref\b[^>]*/\s*>", "", wt, flags=re.IGNORECASE)
    wt = re.sub(r"<ref\b[^>]*>.*?</ref>", "", wt, flags=re.DOTALL | re.IGNORECASE)
    wt = re.sub(r"\{\{FOS\b[^}]*\}\}.*?\{\{FOS\b[^}]*\|\s*end\s*\}\}", "", wt, flags=re.DOTALL | re.IGNORECASE)
    wt = re.sub(
        r"\{\{Вырезанный контент-раздел\b[^}]*\}\}.*?\{\{Вырезанный контент-раздел\b[^}]*\|\s*end\s*\}\}",
        "",
        wt,
        flags=re.DOTALL | re.IGNORECASE,
    )
    wt = re.sub(r"\{\{Вырезанный контент-абзац\|[^{}]*\}\}", "", wt, flags=re.IGNORECASE)
