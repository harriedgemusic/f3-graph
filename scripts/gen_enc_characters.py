    if quests:
        s3_parts.append(f"Связанные задания: {', '.join(f'«{q}»' for q in quests[:4])}.")
    if events:
        s3_parts.append(f"Участвует в событиях: {', '.join(f'«{ev}»' for ev in events[:3])}.")
    sec_habitat = trim_sentences(" ".join(s3_parts), 780)

    entry: dict[str, Any] = {
        "id": nid,
        "role": role,
        "summary": summary,
        "sections": [
            {"title": "Биология и особенности", "text": sec_bio},
            {"title": "Поведение в бою и характеристики", "text": sec_combat},
            {"title": "Ареал обитания и трофеи", "text": sec_habitat},
        ],
        "race": prof["race"],
        "level": level,
        "hp": hp,
        "essential": essential,
        "behavior": format_behavior_field(node, esm),
        "sourceTag": "Fallout 3 ESM + Wiki" if wiki_raw else "Fallout 3 ESM",
    }
    if dmg > 0:
        entry["damage"] = dmg
    if factions:
        entry["factions"] = factions
    if inventory:
        entry["inventory"] = inventory
    if wiki_raw and wiki_raw.get("wikiUrl"):
        entry["wikiUrl"] = wiki_raw["wikiUrl"]

    return entry


