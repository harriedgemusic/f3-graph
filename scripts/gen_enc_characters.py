def clean_factions(raw_factions: list[str]) -> list[str]:
    out: list[str] = []
    seen: set[str] = set()
    for f in raw_factions or []:
        if f in TECH_FACTIONS:
            continue
        mapped = FACTION_MAP.get(f)
        if not mapped:
            # Skip any leftover unmapped internal technical factions containing codes/numbers
            if any(k in f.lower() for k in ("faction", "crime", "voice", "conversation", "ff", "dlc", "cg0", "mq0", "ms", "used for", "friends of", "enemy", "for making")):
                continue
            mapped = f
        if mapped not in seen:
            seen.add(mapped)
            out.append(mapped)
    return out


def clean_location_name(loc: str) -> str | None:
    if not loc:
        return None
    low = loc.lower()
    if any(t in low for t in ("holding pen", "test cell", "sea cave test", "testseacave")):
        return None
    if loc == "Sea Cave":
        return None
    if loc == "Megaton":
        return "Мегатонна"
    if re.fullmatch(r"DC\d+[a-z]?", loc) or loc == "DCStreet02":
        return "Руины Вашингтона"
    cleaned = strip_raw_markup(loc)
    # Strip trailing English parentheticals like "Мегатонна (Megaton)" or "Чеви-Чейз - восток (Chevy Chase)"
    cleaned = re.sub(r"\s*\([A-Za-z0-9\s.'-]+\)$", "", cleaned).strip()
    return cleaned or None


def normalize_quest_title(title: str) -> str:
    """Convert ALL-CAPS Russian quest titles into natural capitalization while keeping acronyms."""
    t = strip_raw_markup(title)
    if not t:
        return ""
    cyr_letters = [c for c in t if "а" <= c.lower() <= "я" or c.lower() == "ё"]
    if cyr_letters and sum(1 for c in cyr_letters if c.isupper()) / len(cyr_letters) > 0.65:
        keep_upper = {"США", "ВРЭ", "ГЭКК", "К.О.З.А.", "РЛ-3", "ZAX", "DLC"}
        words = t.split()
        out = []
        for idx, w in enumerate(words):
            core = w.strip("«»\"'().,!?")
            if core in keep_upper:
                out.append(w)
            elif idx == 0:
                out.append(w.lower().capitalize() if not w.startswith("«") else "«" + w[1:].lower().capitalize())
            else:
                out.append(w.lower())
        res = " ".join(out)
        # Capitalize proper names commonly appearing inside Fallout 3 quest titles
        for proper in ("Адамс", "Атома", "Вашингтон", "Галактики", "Джефферсон", "Дзет", "Кентербери", "Линкольн", "Мегатонн", "Мэриголд", "Оазис", "Питт", "Пойнт-Лукаут", "Пустош", "Ривет-Сити", "Рэйвен-Рок", "Тенпенни", "Трэнквилити-Лейн", "Убежищ", "Чистот"):
            res = re.sub(rf"\b({proper.lower()}[а-яё]*)\b", lambda m: m.group(1).capitalize(), res)
        return res
    return t


