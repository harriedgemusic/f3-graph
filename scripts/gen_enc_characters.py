def verify_output(output: dict[str, dict[str, Any]], expected_ids: set[str]) -> None:
    assert len(output) == 1603, f"Expected 1603 character entries, got {len(output)}"
    assert set(output.keys()) == expected_ids, "Output keys mismatch graph.json character IDs"

    banned_tokens = [
        "{{",
        "}}",
        "[[",
        "]]",
        "<ref",
        "<div",
        "\ufffd",
        "Обитатель Пустоши (",
        "&PCName;",
        "Fallout Shelter",
        "Всадники Постапокалипсиса",
        "Убежища игрока",
        "Fallout 4",
        "Fallout 76",
        "New Vegas",
        "|Имя =",
        ":.",
    ]
    for nid, entry in output.items():
        role = entry.get("role", "")
        summary = entry.get("summary", "")
        sections = entry.get("sections", [])
        assert role and 3 <= len(role.split()) <= 8, f"Bad role word count on {nid}: {role!r}"
        assert len(summary) > 110, f"Short summary ({len(summary)} chars) on {nid}: {summary!r}"
        assert len(sections) >= 2, f"Too few sections on {nid}"
        for sec in sections:
            assert sec.get("title") and len(sec.get("text", "")) >= 100, f"Weak section on {nid}: {sec!r}"
        if "special" in entry:
            sp = entry["special"]
            assert isinstance(sp, list) and len(sp) == 7 and all(isinstance(v, int) for v in sp), f"Bad special on {nid}"
        blob = json.dumps(entry, ensure_ascii=False)
        for tok in banned_tokens:
            assert tok not in blob, f"Banned token {tok!r} found in {nid}"


def main() -> None:
    with open(GRAPH_PATH, encoding="utf-8") as f:
        graph = json.load(f)
    with open(DETAILS_PATH, encoding="utf-8") as f:
        details = json.load(f)
    with open(WALKTHROUGHS_PATH, encoding="utf-8") as f:
        walkthroughs = json.load(f)
    with open(ESM_PATH, encoding="utf-8") as f:
        esm_rich = json.load(f)

    wiki_patched = load_and_patch_wiki()
    nodes_by_id = {n["id"]: n for n in graph["nodes"]}
    wt_by_id = {w["nodeId"]: w for w in walkthroughs if w.get("nodeId")}
    char_nodes = [n for n in graph["nodes"] if n["type"] == "character"]
    char_ids = {n["id"] for n in char_nodes}

    edges_by_char: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for e in graph["edges"]:
        if e["source"] in char_ids:
            edges_by_char[e["source"]].append(e)
        if e["target"] in char_ids and e["target"] != e["source"]:
            edges_by_char[e["target"]].append(e)

    output: dict[str, dict[str, Any]] = {}
    for node in char_nodes:
        nid = node["id"]
        esm = esm_rich[nid]
        det = details.get(nid, {})
        wiki_raw = wiki_patched.get(nid)
        edges = edges_by_char.get(nid, [])
        if node["subtype"] == "creature":
            output[nid] = build_creature_entry(node, esm, det, wiki_raw, edges, nodes_by_id, wt_by_id)
        else:
            output[nid] = build_npc_entry(node, esm, det, wiki_raw, edges, nodes_by_id, wt_by_id)

    verify_output(output, char_ids)

    os.makedirs(OUT_PATH.parent, exist_ok=True)
    with open(OUT_PATH, "w", encoding="utf-8") as f:
        json.dump(output, f, ensure_ascii=False, indent=2)

    wiki_cnt = sum(1 for v in output.values() if v["sourceTag"] == "Fallout 3 ESM + Wiki")
    print(f"[OK] Wrote {len(output)} character encyclopedia entries to {OUT_PATH}")
    print(f"     Wiki-backed: {wiki_cnt} | ESM-only: {len(output) - wiki_cnt}")


if __name__ == "__main__":
    main()
