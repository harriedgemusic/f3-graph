def format_behavior_field(node: dict[str, Any], esm: dict[str, Any]) -> str:
    if node["subtype"] == "creature":
        agg = esm.get("aggression") or "Нейтральный"
        conf = esm.get("confidence") or "Средний"
        return f"{agg}, уверенность: {conf.lower()}"
    beh = esm.get("behavior") or {}
    agg = beh.get("aggression") or "Мирный"
    conf = beh.get("confidence") or "Средний"
    mood = beh.get("mood") or "Нейтральное"
    pkgs = beh.get("packages") or []
    base = f"{agg}, {conf.lower()}; настроение — {mood.lower()}"
    if pkgs:
        base += f". Режим ИИ: {', '.join(pkgs[:5])}"
    return base


def format_special_prose(special: list[int]) -> str:
    labels = [
        ("Сила", special[0]),
        ("Восприятие", special[1]),
        ("Выносливость", special[2]),
        ("Харизма", special[3]),
        ("Интеллект", special[4]),
        ("Ловкость", special[5]),
        ("Удача", special[6]),
    ]
    strong = [f"{name} ({val})" for name, val in labels if val >= 7]
    weak = [f"{name} ({val})" for name, val in labels if val <= 3]
    stat_str = "/".join(str(x) for x in special)
    parts = [f"Базовые параметры S.P.E.C.I.A.L. — {stat_str}."]
    if strong:
        parts.append(f"Наиболее развиты: {', '.join(strong)}.")
    if weak:
        parts.append(f"Слабые стороны: {', '.join(weak)}.")
    return " ".join(parts)


def get_connected_context(
    nid: str,
    edges: list[dict[str, Any]],
    nodes_by_id: dict[str, dict[str, Any]],
    wt_by_id: dict[str, dict[str, Any]],
) -> tuple[list[str], list[str], list[str], list[str]]:
    """Return deduplicated (quests, locations, items, events) linked in graph.json."""
    quests, locs, items, events = [], [], [], []
    seen_q, seen_l, seen_i, seen_e = set(), set(), set(), set()

    for e in edges:
        et = e.get("type")
        other_id = e["target"] if e["source"] == nid else e["source"]
        other = nodes_by_id.get(other_id)
        if not other:
            continue
        if et == "quest_npc":
            if other_id in QUEST_TITLE_OVERRIDES:
                qt = QUEST_TITLE_OVERRIDES[other_id]
            else:
                lbl = strip_raw_markup(other.get("label", ""))
                wt = wt_by_id.get(other_id)
                if lbl and re.search(r"[а-яА-ЯёЁ]", lbl):
                    qt = normalize_quest_title(lbl)
                elif wt and wt.get("title"):
                    qt = normalize_quest_title(wt["title"])
                else:
                    qt = lbl
            if qt and qt not in seen_q:
                seen_q.add(qt)
                quests.append(qt)
        elif et == "npc_location":
            cl = clean_location_name(other.get("label", ""))
            if cl and cl not in seen_l:
                seen_l.add(cl)
                locs.append(cl)
        elif et == "npc_item":
            ci = clean_item_name(other.get("label", ""))
            if ci and ci not in seen_i:
                seen_i.add(ci)
                items.append(ci)
        elif et == "event_entity" and other.get("type") == "event":
            ev = strip_raw_markup(other.get("label", ""))
            if ev and ev not in seen_e:
                seen_e.add(ev)
                events.append(ev)

    return quests, locs, items, events


