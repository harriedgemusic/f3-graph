def build_clean_inventory(det_inv: list[dict[str, Any]], esm_inv: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Preserve {id, label, count} schema from details.json enriched with ESM items."""
    by_id: dict[str, dict[str, Any]] = {}
    order: list[str] = []
    for item in det_inv or []:
        iid = item.get("id")
        if not iid:
            continue
        by_id[iid] = {
            "id": iid,
            "label": clean_item_name(item.get("label", "")),
            "count": int(item.get("count", 1) or 1),
        }
        order.append(iid)
    for item in esm_inv or []:
        iid = item.get("id")
        if not iid or iid in by_id:
            continue
        by_id[iid] = {
            "id": iid,
            "label": clean_item_name(item.get("name", "")),
            "count": int(item.get("count", 1) or 1),
        }
        order.append(iid)
    return [by_id[iid] for iid in order if by_id[iid]["label"]]


def clean_quotes(raw_quotes: list[str], female: bool | None) -> list[str]:
    out: list[str] = []
    seen_norm: set[str] = set()
    for q in raw_quotes or []:
        s = strip_raw_markup(q)
        if len(s) < 18 or len(s) > 220:
            continue
        # Filter obvious gender mismatch in speaker self-reference
        if female is False and re.search(r"\bя\s+(?:это\s+)?(?:сказала|была|видела|сделала|могла)\b", s, re.I):
            continue
        if female is True and re.search(r"\bя\s+(?:это\s+)?(?:сказал|был|видел|сделал|мог)\b", s, re.I):
            continue
        # Avoid nearly identical male/female player-gender variant duplicate lines
        norm_q = re.sub(r"\b(?:сыночек|дочка|он|она|его|её)\b", "*", s.lower())
        if norm_q in seen_norm:
            continue
        seen_norm.add(norm_q)
        out.append(s)
        if len(out) >= 3:
            break
    return out


