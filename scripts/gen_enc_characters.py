def build_role(
    node: dict[str, Any],
    esm: dict[str, Any],
    wiki_lead_clean: str,
    wiki_app: str,
    wiki_cats: list[str],
    clean_factions: list[str],
    locs: list[str],
    creature_kind: str | None,
) -> str:
    edid = node["edid"]
    if edid in CURATED_ROLES_BY_EDID:
        return enforce_word_range(CURATED_ROLES_BY_EDID[edid], ["Пустоши"])

    if node["subtype"] == "creature" and creature_kind:
        lbl = get_display_name(node)
        prof = CREATURE_SPECIES_LORE[creature_kind]
        if "Dead" in edid or "DEAD" in edid or "труп" in lbl.lower():
            return enforce_word_range(f"Погибшая особь вида «{prof['race']}»", ["Пустоши"])
        if "Caravan" in edid:
            return enforce_word_range(f"{lbl} торгового каравана Пустоши", ["Пустоши"])
        if "SwampFolk" in edid or creature_kind == "swampfolk":
            return enforce_word_range(f"Вооружённый дикарь-мутант болот Пойнт-Лукаута ({lbl})", ["Лукаута"])
        if "Turret" in edid or creature_kind == "turret":
            return enforce_word_range(f"Автоматическая охранная {lbl.lower()} защиты", ["комплекса"])
        if "Outcast" in edid:
            return enforce_word_range(f"Перепрограммированный {lbl.lower()} патруля Изгоев", ["Братства"])
        if "Enclave" in edid:
            return enforce_word_range(f"Боевой {lbl.lower()} сил Анклава", ["Пустоши"])
        return enforce_word_range(prof["role"], ["Столичной", "Пустоши"])

    wiki_role = extract_role_from_wiki(wiki_app, wiki_lead_clean, node["dlc"])
    is_dead = "DEAD" in edid or edid.startswith("Dead") or "Dead" in edid
    female = bool(esm.get("female", False))
    if wiki_role and not any(k in edid for k in ("CG00", "CG01", "CG02", "CG03", "CG04", "Vault106", "V106", "DLC04BogCorpse")):
        if len(node["label"].split()) >= 2 or not any(x in edid for x in ("Rifle", "Flamer", "Missile", "Melee", "BigGun", "Patrol")):
            if is_dead and not wiki_role.lower().startswith(("погибш", "мёртв", "мертв")):
                pref = "Погибшая " if female else "Погибший "
                return enforce_word_range(pref + wiki_role[0].lower() + wiki_role[1:], ["Пустоши"])
            return wiki_role

    return build_edid_npc_role(node, esm, clean_factions, locs, wiki_cats)


