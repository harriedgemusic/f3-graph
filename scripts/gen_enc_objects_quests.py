def index_neighbors(graph: dict[str, Any]) -> dict[str, dict[str, list[str]]]:
    """Precompute grouped neighbor labels by node type/key subtype for every node."""
    nodes_by_id = {n["id"]: n for n in graph["nodes"]}
    grouped: dict[str, dict[str, list[str]]] = defaultdict(lambda: defaultdict(list))
    seen: dict[str, set[tuple[str, str]]] = defaultdict(set)

    for e in graph["edges"]:
        s, t, et = e["source"], e["target"], e["type"]
        for src, dst in ((s, t), (t, s)):
            nb = nodes_by_id.get(dst)
            if not nb:
                continue
            bucket = "key" if (et == "object_key" and nb["type"] == "item") else nb["type"]
            raw_lbl = nb["label"]
            if raw_lbl in ("Used for Dialogue Only", "Test") or raw_lbl in TEST_CELLS:
                continue
            lbl = NPC_RU_MAP.get(raw_lbl, raw_lbl) if nb["type"] == "character" else raw_lbl
            if (bucket, lbl) not in seen[src]:
                seen[src].add((bucket, lbl))
                grouped[src][bucket].append(lbl)
    return grouped


def verify_output(result: dict[str, dict[str, Any]], target_nodes: list[dict[str, Any]]) -> None:
    """Enforce strict quality, count, and cleanliness invariants before saving."""
    expected_ids = {n["id"] for n in target_nodes}
    assert len(result) == 1001, f"Expected 1001 entries, got {len(result)}"
    assert set(result.keys()) == expected_ids, "Key mismatch with graph.json target nodes"

    node_by_id = {n["id"]: n for n in target_nodes}
    for nid, entry in result.items():
        node = node_by_id[nid]
        assert entry.get("id") == nid
        assert entry.get("role", "").strip(), f"Empty role on {nid}"
        assert entry.get("sourceTag", "").strip(), f"Empty sourceTag on {nid}"

        summary = entry.get("summary", "")
        assert len(summary) >= 110, f"Summary too short ({len(summary)}) on {nid}: {summary}"

        sections = entry.get("sections", [])
        assert 2 <= len(sections) <= 3, f"Bad section count ({len(sections)}) on {nid}"
        for sec in sections:
            assert sec.get("title", "").strip(), f"Empty section title on {nid}"
            assert len(sec.get("text", "").strip()) >= 60, f"Section text too short on {nid}: {sec}"

        if node["type"] == "quest":
            assert entry.get("questCategory"), f"Missing questCategory on {nid}"
        if node.get("subtype") == "perk":
            assert entry.get("effects"), f"Missing effects on perk {nid}"

        # Serialize entire entry to verify zero raw wikitext, HTML, dev notes, or banned stubs
        blob = json.dumps(entry, ensure_ascii=False)
        for bad in WIKITEXT_MARKERS:
            assert bad not in blob, f"Raw wikitext '{bad}' found in {nid}"
        for bad in FORBIDDEN_STUBS:
            assert bad not in blob, f"Forbidden stub '{bad}' found in {nid}"
        for bad in DEV_NOTE_MARKERS:
            assert bad.lower() not in blob.lower(), f"English dev note '{bad}' found in {nid}"
        for grammar_bad in ("из основной игре", "пункт(а/ов)", "Used for Dialogue Only"):
            assert grammar_bad not in blob, f"Bad string '{grammar_bad}' found in {nid}"
        assert not HTML_TAG_RE.search(blob), f"HTML tag found in {nid}"


def main() -> None:
    graph = json.loads(GRAPH_PATH.read_text(encoding="utf-8"))
    walkthroughs = {w["id"]: w for w in json.loads(WALKTHROUGHS_PATH.read_text(encoding="utf-8"))}
    _details = json.loads(DETAILS_PATH.read_text(encoding="utf-8"))
    esm_rich = json.loads(ESM_RICH_PATH.read_text(encoding="utf-8"))
    wiki_ru = json.loads(WIKI_RU_PATH.read_text(encoding="utf-8"))

    target_nodes = [n for n in graph["nodes"] if n["type"] in ("object", "quest", "event")]
    neighbors = index_neighbors(graph)

    result: dict[str, dict[str, Any]] = {}
    for node in target_nodes:
        nid = node["id"]
        ntype = node["type"]
        nsub = node.get("subtype", "")
        esm_rec = esm_rich.get(nid, {})
        nb_info = neighbors.get(nid, {})
        all_nb_labels = [lbl for lst in nb_info.values() for lbl in lst]

        if ntype == "object":
            wk, is_generic = validate_wiki_match(node, esm_rec, wiki_ru, all_nb_labels)
            if nsub == "perk":
                result[nid] = build_perk_entry(node, esm_rec, wk, nb_info)
            elif nsub == "terminal":
                result[nid] = build_terminal_entry(node, esm_rec, wk, is_generic, nb_info)
            elif nsub == "activator":
                result[nid] = build_activator_entry(node, esm_rec, wk, is_generic, nb_info)
            elif nsub == "container":
                result[nid] = build_container_entry(node, esm_rec, wk, is_generic, nb_info)
            elif nsub == "door":
                result[nid] = build_door_entry(node, esm_rec, wk, is_generic, nb_info)
            else:
                raise ValueError(f"Unknown object subtype {nsub} for {nid}")
        elif ntype == "quest":
            wt = walkthroughs[nid]
            wk, _ = validate_wiki_match(node, esm_rec, wiki_ru, all_nb_labels)
            result[nid] = build_quest_entry(node, esm_rec, wt, wk, nb_info)
        elif ntype == "event":
            result[nid] = build_event_entry(node, esm_rec, nb_info)

    verify_output(result, target_nodes)

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8")
    size_mb = OUT_PATH.stat().st_size / (1024 * 1024)
    print(f"Successfully generated {len(result)} encyclopedia entries -> {OUT_PATH} ({size_mb:.2f} MB)")


if __name__ == "__main__":
    main()
