def build_quest_entry(
    node: dict[str, Any],
    esm_rec: dict[str, Any],
    wt: dict[str, Any],
    wk: dict[str, Any] | None,
    neighbor_info: dict[str, list[str]],
) -> dict[str, Any]:
    """Build complete Russian encyclopedia entry for a Quest node."""
    nid = node["id"]
    edid = node.get("edid", "")
    title = wt.get("title") or node["label"]
    cat = wt.get("category") or node.get("subtype") or "side"
    dlc = node.get("dlc", "base")
    curated = bool(wt.get("curated"))

    custom = NON_CURATED_QUEST_INFO.get(nid)
    role = custom["role"] if custom else QUEST_ROLE_MAP.get(cat, "Задание мира Fallout 3")

    wk_lead = clean_wiki_prose((wk or {}).get("lead", "")) if wk else ""
    wk_secs = extract_wiki_sections_map(wk) if wk else {}

    # Section 1: Сюжетная роль и завязка
    sec1_parts: list[str] = []
    if custom:
        sec1_parts.append(custom["setup"])
    else:
        wt_sum = clean_terminal_markup(wt.get("summary") or "")
        wt_start = clean_terminal_markup(wt.get("startCondition") or "")
        if wt_sum:
            sec1_parts.append(wt_sum)
        if wt_start:
            sec1_parts.append(f"Условие начала: {wt_start}")

        # Add clean Russian ESM objectives if meaningful
        rus_objs = [
            clean_terminal_markup(o["text"]).rstrip(".")
            for o in (esm_rec.get("objectives") or [])
            if o.get("text") and re.search(r"[А-Яа-яЁё]", o["text"])
        ]
        if rus_objs:
            sec1_parts.append("Ключевые этапы журнала заданий: " + "; ".join(rus_objs[:6]) + ".")

        # Enrich with Wiki "Кем даётся" if available
        if "Кем даётся" in wk_secs:
            sec1_parts.append(wk_secs["Кем даётся"])

    if custom and wk_lead and "вырезан" not in custom["summary"].lower():
        if "Кем даётся" in wk_secs:
            sec1_parts.append(wk_secs["Кем даётся"])

    # Section 2: Участники, ключевые решения и награды
    sec2_parts: list[str] = []
    if custom:
        sec2_parts.append(custom["outcome"])
    else:
        steps = wt.get("steps") or []
        branch_texts: list[str] = []
        skill_checks: list[str] = []
        for st in steps:
            for sc in st.get("skillChecks") or []:
                if sc and sc not in skill_checks:
                    skill_checks.append(sc)
            for br in st.get("branches") or []:
                lbl = br.get("label", "").strip()
                bsum = br.get("summary", "").strip()
                bout = br.get("outcome", "").strip()
                if lbl and (bsum or bout):
                    branch_texts.append(f"«{lbl}» — {bsum} {bout}".strip())

        if branch_texts:
            sec2_parts.append("Основные варианты решений и развилки:\n• " + "\n• ".join(branch_texts[:5]))
        elif steps:
            step_titles = [f"«{s['title']}»" for s in steps[:5] if s.get("title")]
            if step_titles:
                sec2_parts.append(f"Прохождение последовательно разворачивается через следующие узловые эпизоды: {', '.join(step_titles)}.")

        if skill_checks:
            sec2_parts.append(f"Важные проверки навыков и характеристик: {', '.join(skill_checks[:6])}.")

        rewards = [clean_terminal_markup(r) for r in (wt.get("rewards") or []) if r]
        if rewards:
            sec2_parts.append("Награды и итоги: " + "; ".join(rewards[:6]) + ".")

    if wk_secs.get("Получение награды") and not custom:
        rew_txt = wk_secs["Получение награды"]
        if len(rew_txt) > 500:
            rew_txt = re.split(r"(?<=[.!?])\s+", rew_txt)
            rew_txt = " ".join(rew_txt[:3])
        sec2_parts.append(rew_txt)

    # Connected graph entities
    npcs = neighbor_info.get("character", [])
    locs = clean_places_list(neighbor_info.get("location", []), limit=6)
    items = neighbor_info.get("item", [])
    chain_q = neighbor_info.get("quest", [])
    rel_bits: list[str] = []
    if npcs:
        rel_bits.append(f"действующие лица — {', '.join(npcs[:6])}")
    if locs:
        rel_bits.append(f"локации — {', '.join(locs[:5])}")
    if items:
        rel_bits.append(f"предметы и трофеи — {', '.join(items[:5])}")
    if chain_q:
        rel_bits.append(f"связанные миссии — {', '.join(f'«{q}»' for q in chain_q[:4])}")
    if rel_bits:
        sec2_parts.append("Ключевые связи миссии: " + "; ".join(rel_bits) + ".")

    sections: list[dict[str, str]] = [
        {"title": "Сюжетная роль и завязка", "text": fix_russian_punctuation("\n\n".join(sec1_parts))},
        {"title": "Участники, ключевые решения и награды", "text": fix_russian_punctuation("\n\n".join(sec2_parts))},
    ]

    # Optional 3rd section for missable warnings & wiki notes
    extra_notes: list[str] = []
    for mw in wt.get("missableWarnings") or []:
        if mw:
            extra_notes.append(mw)
    if "Заметки" in wk_secs:
        z_txt = wk_secs["Заметки"]
        if len(z_txt) > 650:
            z_txt = " ".join(re.split(r"(?<=[.!?])\s+", z_txt)[:4])
        extra_notes.append(z_txt)
    if extra_notes:
        sections.append({"title": "Скрытые детали и предупреждения", "text": fix_russian_punctuation("\n\n".join(extra_notes))})

    # Summary (rich 2-4 sentences > 110 chars)
    if custom:
        summary = custom["summary"]
    else:
        wt_sum = clean_terminal_markup(wt.get("summary") or "")
        wt_start = clean_terminal_markup(wt.get("startCondition") or "")
        rew_preview = ", ".join((wt.get("rewards") or [])[:2])
        s1 = wt_sum if len(wt_sum) >= 90 else f"«{title}» — {lower_first(role)} ({DLC_GEN.get(dlc, 'Fallout 3')}). {wt_sum}"
        s2 = f"Открывается: {wt_start}" if wt_start and wt_start.lower() not in s1.lower() else ""
        s3 = f"В числе наград и последствий: {rew_preview}." if rew_preview else ""
        summary = fix_russian_punctuation(" ".join(x for x in (s1, s2, s3) if x))
        if len(summary) < 115 and locs:
            summary = f"{summary} Основные события затрагивают локации: {', '.join(locs[:3])}."

    tags = ["ESM"]
    if curated:
        tags.append("Прохождение")
    elif custom:
        tags.append("Справка")
    if wk:
        tags.append("Wiki")

    entry: dict[str, Any] = {
        "id": nid,
        "role": role,
        "questCategory": cat,
        "summary": summary,
        "sections": sections,
        "sourceTag": "+".join(tags),
    }
    if wk and wk.get("wikiUrl"):
        entry["wikiUrl"] = wk["wikiUrl"]
    return entry


