def clean_terminal_markup(text: str) -> str:
    """Strip HTML tags/entities and normalize terminal angle-bracket UI tags."""
    if not text:
        return ""
    s = html.unescape(text)
    s = re.sub(r"<!--.*?-->", "", s, flags=re.DOTALL)
    s = re.sub(r"<br\s*/?>", "\n", s, flags=re.IGNORECASE)
    s = HTML_TAG_RE.sub("", s)
    # Replace Fallout 3 terminal control markers <!>foo<!> -> «foo» or [!]
    s = re.sub(r"<!>(.*?)<!>", lambda m: f"«{m.group(1).strip()}»" if m.group(1).strip() else "[!]", s)
    s = s.replace("<!>", "[!]")
    s = re.sub(r"<\s*!\s*!\s*!\s*!\s*!\s*>", "[ВНИМАНИЕ]", s)
    # Replace remaining <...> angle UI labels (not HTML) with [...]
    s = re.sub(r"<([^<>\n]{1,64})>", r"[\1]", s)
    # Remove any accidental double-brace/bracket markers (e.g. corrupted ESM glitch text &#}})
    s = s.replace("{{", "(").replace("}}", ")").replace("[[", "[").replace("]]", "]")
    s = re.sub(r"[ \t]+\n", "\n", s)
    s = re.sub(r"\n{3,}", "\n\n", s)
    return re.sub(r"[ \t]{2,}", " ", s).strip()


def strip_wikitext_residuals(text: str) -> str:
    """Defensively clean any residual wiki markup or ref tags."""
    if not text:
        return ""
    s = html.unescape(text)
    s = re.sub(r"<ref[^>]*>.*?</ref>", "", s, flags=re.DOTALL | re.IGNORECASE)
    s = re.sub(r"<ref[^>]*/>", "", s, flags=re.IGNORECASE)
    s = re.sub(r"\{\{.*?\}\}", "", s, flags=re.DOTALL)
    s = re.sub(r"\[\[(?:[^|\]]*\|)?([^\]]+)\]\]", r"\1", s)
    s = s.replace("{{", "").replace("}}", "").replace("[[", "").replace("]]", "")
    s = clean_terminal_markup(s)
    return s


def filter_russian_sentences(text: str) -> str:
    """Remove English GECK/developer notes and lines lacking Cyrillic."""
    if not text:
        return ""
    out_lines: list[str] = []
    for raw_line in text.splitlines():
        line = raw_line.strip()
        if not line:
            continue
        low = line.lower()
        if any(m.lower() in low for m in DEV_NOTE_MARKERS):
            continue
        if not re.search(r"[А-Яа-яЁё]", line):
            continue
        out_lines.append(line)
    return "\n".join(out_lines).strip()


def plural_ru(n: int, form1: str, form2: str, form5: str) -> str:
    """Return proper Russian plural noun form for integer n."""
    n_abs = abs(n) % 100
    if 11 <= n_abs <= 19:
        return form5
    last = n_abs % 10
    if last == 1:
        return form1
    if 2 <= last <= 4:
        return form2
    return form5


def lower_first(s: str) -> str:
    """Lowercase only the first character of a Russian string."""
    return (s[0].lower() + s[1:]) if s else ""


def fix_russian_punctuation(text: str) -> str:
    """Clean stray double periods, awkward spacing, and redundant terminal punctuation."""
    if not text:
        return ""
    s = text
    # Fix abbreviations/titles ending with '.' followed by another '.' (but keep '...')
    s = re.sub(r"(?<!\.)\.\.(?!\.)", ".", s)
    # Remove stray comma-dot or dot-comma after normal words (preserving V.A.T.S., S.P.E.C.I.A.L., т.д., etc.)
    s = re.sub(r"([а-яёa-z]{3,})\.,", r"\1,", s)
    s = s.replace(",.", ",").replace(";;", ";").replace(".;", ";")
    s = re.sub(r"[ \t]{2,}", " ", s)
    return s.strip()


def clean_wiki_prose(text: str, drop_terminal_dumps: bool = False) -> str:
    """Clean Fallout Wiki RU prose for strictly Fallout 3 encyclopedia display."""
    s = strip_wikitext_residuals(text)
    if not s:
        return ""

    # Clean common cross-game mentions in lead sentences
    s = re.sub(
        r"\bFallout\s*3\s*(?:,|и)\s*Fallout:\s*New\s*Vegas(?:\s*(?:,|и)\s*Fallout\s*[476]+)*(?:\s*и\s*Contraptions\s*Workshop)?",
        "Fallout 3",
        s,
        flags=re.IGNORECASE,
    )
    s = re.sub(
        r"(?:в\s+серии\s+игр\s+Fallout|серии\s+игр\s+Fallout)",
        "мире Fallout 3",
        s,
        flags=re.IGNORECASE,
    )
    # Remove English parenthetical translations and residual wiki pipe markup
    s = re.sub(r"\s*\(англ\.[^)]+\)", "", s, flags=re.IGNORECASE)
    s = re.sub(r"\bЗаметка\|текст\b", "", s, flags=re.IGNORECASE)
    # Remove references to unseen wiki layout elements
    s = re.sub(
        r"\(?(?:см\.?\s*(?:ниже|таблицу|галерею|карту|изображение)[^)]*\)?|на\s+(?:карте|изображении)\s*(?:справа|слева|ниже)|приведенн(?:ой|ом|ых)\s+справа|в\s+таблице\s+(?:ниже|справа))",
        "",
        s,
        flags=re.IGNORECASE,
    )

    clean_lines: list[str] = []
    skip_other_game_block = False
    for raw_line in s.splitlines():
        line = raw_line.strip()
        if not line:
            continue
        if re.match(r"^Fallout\s*3\s*:\s*$", line, re.IGNORECASE) or line in ("Заметки:", "Описание:", "Эффект:", "Примечания:"):
            skip_other_game_block = False
            if re.match(r"^Fallout\s*3\s*:\s*$", line, re.IGNORECASE):
                continue
        elif OTHER_GAME_BLOCK_HDR_RE.match(line):
            skip_other_game_block = True
            continue
        if skip_other_game_block:
            continue

        # Drop wiki disambiguation / meta headers / raw template residue
        if line.startswith(("• Если вы искали", "Если вы искали", "Эта статья содержит записи в терминалах", "Пунктуация и орфография записей сохранены", "Главное меню ")):
            continue
        # Drop raw terminal dumps (> [Запись]...)
        if drop_terminal_dumps and (line.startswith(">") or (line.startswith("[") and line.endswith("]"))):
            continue
        # Drop bullets or lines explicitly about other Fallout games or test/guide citations
        if OTHER_GAME_RE.search(line):
            sents = re.split(r"(?<=[.!?])\s+", line)
            kept_sents = [st for st in sents if st.strip() and not OTHER_GAME_RE.search(st)]
            if not kept_sents:
                continue
            line = " ".join(kept_sents)
        if re.search(r"[А-Яа-яЁё]", line):
            clean_lines.append(line)

    res = "\n".join(clean_lines)
    res = re.sub(r"[ \t]{2,}", " ", res)
    res = re.sub(r"\s+([,.;:!?])", r"\1", res)
    return fix_russian_punctuation(res)


def translate_location_name(loc: str) -> str:
    """Translate known raw English cell names and drop developer test cells."""
    if not loc or loc in TEST_CELLS:
        return ""
    if loc in CELL_RU_MAP:
        return CELL_RU_MAP[loc]
    # Trim noisy English parenthesis suffix if identical Russian precedes it
    return re.sub(r"\s*\([A-Za-z0-9' .-]+\)$", "", loc).strip() or loc


def clean_places_list(places: list[str], limit: int = 8) -> list[str]:
    """Return deduplicated Russian placement names excluding dev test cells."""
    out: list[str] = []
    seen: set[str] = set()
    for p in places:
        tr = translate_location_name(p)
        if not tr:
            continue
        key = tr.lower()
        if key not in seen:
            seen.add(key)
            out.append(tr)
            if len(out) >= limit:
                break
    return out


def format_places_phrase(places: list[str], fallback: str = "в ключевых локациях Столичной Пустоши") -> str:
    """Format a natural Russian list of locations."""
    if not places:
        return fallback
    if len(places) == 1:
        return f"в локации «{places[0]}»"
    if len(places) == 2:
        return f"в локациях «{places[0]}» и «{places[1]}»"
    shown = ", ".join(f"«{p}»" for p in places[:4])
    extra = f" и ещё {len(places) - 4} точках" if len(places) > 4 else ""
    return f"в следующих локациях: {shown}{extra}"


