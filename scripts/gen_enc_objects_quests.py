def build_activator_entry(
    node: dict[str, Any],
    esm_rec: dict[str, Any],
    wk: dict[str, Any] | None,
    is_generic_wiki: bool,
    neighbor_info: dict[str, list[str]],
) -> dict[str, Any]:
    """Build complete Russian encyclopedia entry for an Activator node."""
    nid = node["id"]
    edid = node.get("edid", "")
    label = node["label"]
    dlc = node.get("dlc", "base")
    lock_diff = esm_rec.get("lockDiff") or ""
    req_key = esm_rec.get("requiredKey") or ""
    raw_text = clean_terminal_markup(esm_rec.get("text") or "")

    places = clean_places_list(esm_rec.get("placements") or [])
    if not places:
        places = clean_places_list(neighbor_info.get("location", []))
    quests = neighbor_info.get("quest", [])
    events = neighbor_info.get("event", [])
    npcs = neighbor_info.get("character", [])
    keys = neighbor_info.get("key", [])

    role, mech_desc, unlocks_list = _describe_activator_mechanics(node, esm_rec, places, quests)

    sec1_parts: list[str] = [mech_desc]
    if lock_diff:
        sec1_parts.append(f"Доступ ограничен уровнем сложности «{lock_diff}»" + (f" (подходит ключ «{req_key}»)." if req_key else "."))
    if raw_text:
        sec1_parts.append(f"Внутриигровое описание / метка объекта: «{raw_text}».")

    wk_secs = extract_wiki_sections_map(wk) if wk else {}
    if wk and not is_generic_wiki:
        for h in ("Описание", "Квесты", "Заметки"):
            if h in wk_secs:
                sec1_parts.append(wk_secs[h])
                break

    sec2_parts: list[str] = []
    sec2_parts.append(
        f"В ресурсах игры объект «{label}» (EDID: {edid}) входит в состав {DLC_GEN.get(dlc, 'Fallout 3')} и встречается {format_places_phrase(places, 'в специальных сценах и интерьерных ячейках')}."
    )
    if wk and not is_generic_wiki and "Квесты" in wk_secs and wk_secs["Квесты"] not in sec1_parts:
        sec2_parts.append(wk_secs["Квесты"])
    elif wk and is_generic_wiki and "Описание" in wk_secs:
        sec2_parts.append(wk_secs["Описание"])

    links_bits: list[str] = []
    if quests:
        links_bits.append(f"связанные миссии: {', '.join(f'«{q}»' for q in quests[:5])}")
    if events:
        links_bits.append(f"события: {', '.join(f'«{e}»' for e in events[:3])}")
    if npcs:
        links_bits.append(f"персонажи: {', '.join(npcs[:4])}")
    if keys:
        links_bits.append(f"ключи доступа: {', '.join(f'«{k}»' for k in keys[:3])}")
    if links_bits:
        sec2_parts.append("Связи в графе мира: " + "; ".join(links_bits) + ".")
    else:
        sec2_parts.append("Объект взаимодействует с окружением локации напрямую и не привязан к отдельным квестовым триггерам журнала.")

    # Rich 2-4 sentence summary
    s1 = f"«{label}» — {lower_first(role)} в {DLC_PREP.get(dlc, 'Fallout 3')}."
    first_mech = re.split(r"(?<=[.!?])\s+", mech_desc)
    s2 = " ".join(first_mech[:2])
    if quests:
        s3 = f"Встречается {format_places_phrase(places, 'в ключевой зоне')} и напрямую задействован в миссии «{quests[0]}»."
    elif events:
        s3 = f"Размещён {format_places_phrase(places, 'в зоне события')} и связан с эпизодом «{events[0]}»."
    else:
        s3 = f"Объект размещён {format_places_phrase(places, 'в интерьерах мира')} и используется при исследовании и взаимодействии с окружением."

    summary = fix_russian_punctuation(f"{s1} {s2} {s3}")
    if req_key and f"Требуется ключ: {req_key}" not in unlocks_list:
        unlocks_list = list(unlocks_list) + [f"Требуется ключ: {req_key}"]

    source_tag = "ESM+Wiki" if (wk and not is_generic_wiki) else "ESM"
    entry: dict[str, Any] = {
        "id": nid,
        "role": role,
        "summary": summary,
        "sections": [
            {"title": "Назначение и особенности", "text": fix_russian_punctuation("\n\n".join(sec1_parts))},
            {"title": "Расположение и содержимое / связь", "text": fix_russian_punctuation("\n\n".join(sec2_parts))},
        ],
        "sourceTag": source_tag,
    }
    if lock_diff:
        entry["lockDiff"] = lock_diff
    if raw_text:
        entry["text"] = raw_text
    if unlocks_list:
        entry["unlocks"] = unlocks_list
    if wk and not is_generic_wiki and wk.get("wikiUrl"):
        entry["wikiUrl"] = wk["wikiUrl"]
    return entry


