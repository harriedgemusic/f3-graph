def validate_wiki_match(
    node: dict[str, Any],
    esm_rec: dict[str, Any],
    wiki: dict[str, Any],
    neighbor_labels: list[str],
) -> tuple[dict[str, Any] | None, bool]:
    """Return (validated_wiki_record, is_generic_class) avoiding false positives."""
    nid = node["id"]
    wk = wiki.get(nid)
    if not wk:
        return None, False

    wtitle = wk.get("wikiTitle", "")
    wlow = wtitle.lower()
    sub = node.get("subtype", "")
    edlow = (node.get("edid") or "").lower()

    # Point Lookout hallucinatory bog bobbleheads aren't the real S.P.E.C.I.A.L. bobbleheads
    if sub == "activator" and "bogbobble" in edlow:
        return None, False

    # ForgeMechanistDoorSwitch01 is a secret door trigger, not an ordinary coffee brewer
    if sub == "activator" and "mechanistdoorswitch" in edlow:
        return None, False

    # Validate location-bound terminal wiki articles
    if sub == "terminal":
        haystack = " ".join(
            [
                edlow,
                (node.get("label") or "").lower(),
                (esm_rec.get("text") or "").lower(),
                " ".join(p.lower() for p in esm_rec.get("placements", [])),
                " ".join(lb.lower() for lb in neighbor_labels),
            ]
        )
        for loc_kw, required_tokens in TERMINAL_LOCATION_CHECKS:
            if loc_kw in wlow:
                if not any(tok in haystack for tok in required_tokens):
                    return None, False

    is_generic = wtitle in GENERIC_WIKI_TITLES
    return wk, is_generic


def extract_wiki_sections_map(wk: dict[str, Any] | None) -> dict[str, str]:
    """Extract cleaned section heading -> text mapping from a wiki entry."""
    if not wk:
        return {}
    out: dict[str, str] = {}
    for sec in wk.get("sections", []):
        h = (sec.get("heading") or "").strip()
        if not h:
            continue
        if OTHER_GAME_RE.search(h) and "fallout 3" not in h.lower():
            continue
        txt = clean_wiki_prose(sec.get("text", ""))
        if txt:
            if h in out:
                if txt not in out[h]:
                    out[h] = f"{out[h]}\n\n{txt}"
            else:
                out[h] = txt
    return out


def match_compendium_terminal_section(
    node: dict[str, Any],
    esm_rec: dict[str, Any],
    wk: dict[str, Any] | None,
) -> str:
    """For multi-terminal location wiki pages, extract the section belonging to this terminal."""
    if not wk:
        return ""
    secs = wk.get("sections", [])
    if not secs:
        return ""
    lbl = (node.get("label") or "").lower()
    menu_titles = [m.get("title", "").lower() for m in esm_rec.get("menuItems", []) if m.get("title")]

    best_score = 0
    best_txt = ""
    for sec in secs:
        h = (sec.get("heading") or "").lower()
        raw_t = sec.get("text", "")
        t_low = raw_t.lower()
        score = 0
        if lbl and lbl in h:
            score += 4
        for mt in menu_titles[:4]:
            if len(mt) >= 5 and mt in t_low:
                score += 3
        if score > best_score:
            cleaned = clean_wiki_prose(raw_t, drop_terminal_dumps=True)
            if len(cleaned) >= 40:
                best_score = score
                best_txt = cleaned
    return best_txt if best_score >= 3 else ""


